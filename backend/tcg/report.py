"""Exports: graph.json (the full temporal graph) and REPORT.md (a Graphify-style report with a temporal section)."""

from __future__ import annotations

from datetime import datetime, timezone


def _d(ts: int) -> str:
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d")


def _short(key: str) -> str:
    return key.split("::", 1)[1] if "::" in key else key


def markdown(repo: dict, gh: dict, stats: dict) -> str:
    k = stats["kpis"]
    comms = {c["id"]: c for c in stats["communities"]}
    L = []
    L.append(f"# TCG report: {repo['name']}\n")
    if gh.get("description"):
        L.append(f"> {gh['description']}\n")
    L.append(f"Temporal code graph over **{k['commits']} first-parent commits** "
             f"({_d(k['first_ts'])} → {_d(k['last_ts'])}, {k['span_days']} days). "
             f"Every node and edge carries the commit interval over which it held.\n")
    L.append("## At a glance\n")
    L.append("| Metric | Now | Change over window |\n|---|---:|---:|")
    L.append(f"| Files | {k['files']} | {k['files_delta']:+d} |")
    L.append(f"| Symbols (classes, functions, methods) | {k['symbols']} | {k['symbols_delta']:+d} |")
    L.append(f"| Structural edges (calls, imports, inherits) | {k['edges']} | {k['edges_delta']:+d} |")
    L.append(f"| Co-change pairs | {k['cochange_pairs']} | {k['cochange_strong']} co-changed 3+ times |")
    L.append(f"| Edges opened / closed in window | {k['edges_opened']} / {k['edges_closed']} | |")
    L.append(f"| Communities | {k['communities']} | |")
    L.append(f"| Contributors | {k['contributors']} | |\n")

    L.append("## God nodes\n")
    L.append("The most central symbols by PageRank: most of the system flows through them.\n")
    L.append("| # | Symbol | Kind | Callers | Degree | Community |\n|---:|---|---|---:|---:|---|")
    for i, g in enumerate(stats["god_nodes"][:10], 1):
        c = comms.get(g["community"], {}).get("label", "–")
        L.append(f"| {i} | `{g['qual'] or g['name']}` ({g['path']}) | {g['kind']} | {g['callers']} | {g['degree']} | {c} |")
    L.append("")

    L.append("## Communities\n")
    for c in stats["communities"][:12]:
        if c["size"] < 3:
            continue
        tops = ", ".join(f"`{_short(t)}`" for t in c["top"][:4])
        L.append(f"- **{c['label']}**: {c['size']} symbols in {c['files']} files. Hubs: {tops}")
    L.append("")

    L.append("## Hidden coupling (history only)\n")
    L.append("Pairs that keep changing together but have no import, call or inheritance link. "
             "A snapshot graph cannot see these.\n")
    for h in [h for h in stats["hidden_coupling"]["files"] if not h.get("aux")][:10]:
        L.append(f"- `{h['a']}` ⇄ `{h['b']}`: co-changed {h['times']}× (w = {h['weight']})")
    for h in [h for h in stats["hidden_coupling"]["symbols"] if not h.get("aux")][:8]:
        L.append(f"- `{_short(h['a'])}` ⇄ `{_short(h['b'])}`: co-changed {h['times']}× (w = {h['weight']})")
    L.append("")

    L.append("## Churn hotspots\n")
    L.append("Ranked by the recency-decayed change prior h(v; τ), λ = "
             f"{stats['params']['lambda']} commits.\n")
    for h in stats["hotspots"]["symbols"][:10]:
        L.append(f"- `{h['name']}` ({h['path']}): {h['changes']} changes, h = {h['prior']}")
    L.append("")

    L.append("## Surprising connections\n")
    for s in stats["surprising"][:8]:
        ca, cb = comms.get(s["ca"], {}).get("label", "?"), comms.get(s["cb"], {}).get("label", "?")
        L.append(f"- `{_short(s['a'])}` → `{_short(s['b'])}` ({s['type']}) crosses *{ca}* → *{cb}*")
    L.append("")

    lt = stats["lifetimes"]
    L.append("## How long does structure last?\n")
    if lt["survival_rate"] is not None:
        L.append(f"Of {lt['born_in_window']} edges created inside the window, "
                 f"{round(100 * lt['survival_rate'])}% are still alive at the newest commit.")
    for t, m in lt["median_closed"].items():
        if m is not None:
            L.append(f"- median lifetime of a closed `{t}` edge: {m} commits")
    L.append("")

    L.append("## Biggest commits by symbols touched (|Δ_t|)\n")
    for b in stats["biggest_commits"][:6]:
        L.append(f"- `{b['sha'][:7]}` {b['msg']} ({b['delta']} symbols, {b['author']})")
    L.append("")

    L.append("## Suggested questions\n")
    for q in stats["questions"]:
        L.append(f"- {q}")
    L.append("\n---\nGenerated by TCG Studio. The history was read only along the first-parent chain, so it is leakage-safe for any τ in the window.\n")
    return "\n".join(L)
